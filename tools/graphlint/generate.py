# -*- coding: utf-8 -*-
"""从 edge-signatures.yaml 生成 graph.schema.json 的边约束与 object-model.md 的两张表。"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from .signatures import (ANY, DOC_PATH, GRAPH_SCHEMA_PATH, REPO_ROOT, Signatures, load)

BLOCK_RE = re.compile(
    r"(<!-- GENERATED:(?P<name>[a-z-]+) BEGIN[^>]*-->)(?P<body>.*?)(<!-- GENERATED:(?P=name) END -->)",
    re.S,
)

SCHEMA_COMMENT = ("GENERATED by tools/graphlint generate from "
                  "spec/framework/edge-signatures.yaml —— 勿手改；改表后重新生成。")


def _order(sig: Signatures) -> dict[str, int]:
    return {name: i for i, name in enumerate(sig.node_classes)}


def _classes(sig: Signatures, names: tuple[str, ...]) -> str:
    order = _order(sig)
    return " / ".join(sig.abbr(n) for n in sorted(names, key=lambda x: order.get(x, 99)))


def _ranges_label(sig: Signatures, esig) -> str:
    if ANY in esig.ranges:
        if esig.excluded_to:
            return f"任意对象（不含 {_classes(sig, esig.excluded_to)}）"
        return "任意对象"
    return _classes(sig, esig.ranges)


def _attrs(esig) -> str:
    parts: list[str] = []
    for attr in esig.attributes:
        c = attr.constraint
        if attr.name == "weight":
            parts.append("`weight` 必填" if attr.required else "`weight`（可选，默认 0.5）")
        elif "enum" in c:
            text = "`%s` ∈ %s" % (attr.name, " / ".join(f"`{v}`" for v in c["enum"]))
            if attr.required:
                text += "（必填）"
            parts.append(text)
        else:
            parts.append(f"`{attr.name}`" + ("（必填）" if attr.required else ""))
    if esig.time_required:
        parts.append("`time` 必填（可一端 `null`）")
    return "；".join(parts) or "—"


def render_edge_table(sig: Signatures) -> str:
    lines = [
        "| # | `type` | 方向 | from → to | 专属属性 | 用途 |",
        "|---:|---|---|---|---|---|",
    ]
    for i, esig in enumerate(sig.edges.values(), 1):
        left = _classes(sig, esig.domains)
        right = "同类型" if esig.same_class else _ranges_label(sig, esig)
        lines.append(
            f"| {i} | `{esig.type}` | {esig.direction} | {left} → {right} | "
            f"{_attrs(esig)} | {esig.gloss} |"
        )
    return "\n".join(lines)


def render_constraints(sig: Signatures) -> str:
    lines = [
        "| 边类型 | 允许 from | 允许 to | 明确禁止 |",
        "|---|---|---|---|",
    ]
    for esig in sig.edges.values():
        lines.append(
            f"| `{esig.type}` | {_classes(sig, esig.domains)} | {_ranges_label(sig, esig)} | "
            f"{esig.forbid} |"
        )
    return "\n".join(lines)


def render_invariants(sig: Signatures) -> str:
    lines: list[str] = []
    for i, inv in enumerate(sig.invariants, 1):
        lines.append(f"{i}. **{inv.get('name', inv.get('id'))}**（`{inv['id']}`）· "
                     f"级别 `{inv.get('level', 'error')}` · 判定：{inv.get('detection', '')}")
        if inv.get("rule"):
            lines.append(f"   - 规则：{inv['rule']}")
        applies = inv.get("applies_to") or ()
        if applies:
            if tuple(applies) == ("*",):
                lines.append("   - 适用：所有边")
            else:
                lines.append("   - 适用：" + "、".join(f"`{a}`" for a in applies))
        for rule in inv.get("rules") or ():
            rid = rule.get("id", "rule")
            level = rule.get("level", "error")
            if "pair" in rule:
                pair = " + ".join(f"`{p}`" for p in rule["pair"])
                lines.append(f"   - {pair}（同一 from→to）· 级别 `{level}`：{rule.get('message', '')}")
            else:
                lines.append(f"   - `{rid}` · 级别 `{level}`：当 {rule.get('when', '')}，"
                             f"要求 {rule.get('require', '')}。消息：{rule.get('message', '')}")
            if rule.get("note"):
                lines.append(f"     - 说明：{rule['note']}")
    return "\n".join(lines)


def _pattern_block(sig: Signatures, names: tuple[str, ...]) -> dict[str, Any] | None:
    if ANY in names:
        return None
    pats = [sig.node_classes[n]["pattern"] for n in names]
    if len(pats) == 1:
        return {"pattern": pats[0]}
    return {"anyOf": [{"pattern": p} for p in pats]}


def _excluded_block(sig: Signatures, excluded: tuple[str, ...]) -> dict[str, Any] | None:
    if not excluded:
        return None
    prefixes = "|".join(re.escape(sig.node_classes[c]["prefix"]) for c in excluded)
    return {"pattern": f"^(?!(?:{prefixes}))"}


def _edge_rule(sig: Signatures, esig) -> dict[str, Any]:
    props: dict[str, Any] = {"directed": {"const": esig.directed}}
    from_block = _pattern_block(sig, esig.domains)
    if from_block:
        props["from"] = from_block
    to_block = _pattern_block(sig, esig.ranges)
    if to_block is None and esig.excluded_to:
        to_block = _excluded_block(sig, esig.excluded_to)
    if to_block:
        props["to"] = to_block
    required = []
    for attr in esig.attributes:
        c = dict(attr.constraint)
        props[attr.name] = c
        if attr.required:
            required.append(attr.name)
    if esig.time_required:
        props["time"] = {"anyOf": [
            {"properties": {"from": {"type": "integer"}}},
            {"properties": {"to": {"type": "integer"}}},
            {"properties": {"precision": {"const": "unknown"}}},
        ]}
    then: dict[str, Any] = {"properties": props}
    if required:
        then["required"] = required
    return {
        "if": {"properties": {"type": {"const": esig.type}}, "required": ["type"]},
        "then": then,
    }


def _base_schema_rules(sig: Signatures) -> list[dict[str, Any]]:
    """按 edge_schema_rules 的顺序，从条件规则里取出各自的 schema 片段。"""
    order = sig.raw.get("edge_schema_rules") or []
    if not order:
        raise SystemExit("edge-signatures.yaml 缺少 edge_schema_rules")
    by_id = {rule.get("id"): rule for rule in sig.conditional_rules}
    rules: list[dict[str, Any]] = []
    seen: set[str] = set()
    for rid in order:
        if rid in seen:
            raise SystemExit(f"edge_schema_rules 重复引用：{rid}")
        seen.add(rid)
        rule = by_id.get(rid)
        if rule is None:
            raise SystemExit(f"edge_schema_rules 引用了不存在的条件规则：{rid}")
        schema = rule.get("schema")
        if not isinstance(schema, dict):
            raise SystemExit(f"条件规则 {rid} 缺少 schema 块")
        rules.append(schema)
    return rules


def build_schema(sig: Signatures) -> dict[str, Any]:
    data = json.loads(GRAPH_SCHEMA_PATH.read_text(encoding="utf-8"))
    edge_def = data.setdefault("$defs", {}).setdefault("edge", {})
    edge_def["$comment"] = SCHEMA_COMMENT
    edge_def.setdefault("properties", {}).setdefault("type", {})["enum"] = list(sig.edges)
    edge_def["required"] = ["id", "from", "to", "type", "directed"]
    props = edge_def.setdefault("properties", {})
    props.clear()
    props.update({
        "id": {"type": "string", "pattern": "^E:[^>]+>[a-z_]+>[^>]+(#[0-9]+)?$"},
        "from": {"type": "string", "minLength": 1},
        "to": {"type": "string", "minLength": 1},
        "type": {"enum": list(sig.edges)},
        "directed": {"type": "boolean"},
        "time": {"$ref": "#/$defs/time"},
        "source": {"$ref": "#/$defs/source"},
        "claimant": {"type": ["string", "null"]},
        "grade": {"enum": ["A", "S", "U", "F"]},
        "attestation": {"enum": ["direct", "contemporary_report", "later_report",
                                 "textbook_simplification", "unknown"]},
        "confidence": {"type": "number", "minimum": 0, "maximum": 1},
        "weight": {"type": ["number", "null"], "exclusiveMinimum": 0, "maximum": 1},
        "kind": {"enum": ["taxonomic", "historical", "institutional", "overlaps",
                          "prerequisite", "method_source", "shared_object", None]},
        "role": {"type": ["string", "null"]},
        "text_ref": {"type": ["string", "null"], "pattern": "^doc:.+#.+$"},
        "note": {"type": "string", "maxLength": 280},
        "claims": {"type": "array", "items": {"type": "string",
                  "pattern": "^CLM:[A-Za-z0-9:._-]+\\.[0-9]+$"}},
        "skeleton_kind": {"enum": ["direct", "contradiction", "construction", "induction",
                                   "descent", "exhaustion", "algebraic_identity", "case_split",
                                   "extremal", "limit", "other"]},
        "similarity": {"type": "number", "minimum": 0, "maximum": 1},
        "conclusion_match": {"type": "boolean"},
        "specificity": {"type": "number", "minimum": 0, "maximum": 1},
        "trace_refs": {"type": "array", "items": {"type": "string", "pattern": "^doc:.+#.+$"}},
    })

    base_rules = _base_schema_rules(sig)
    per_edge = [_edge_rule(sig, esig) for esig in sig.edges.values()]
    evidence_types = [e.type for e in sig.edges.values() if e.evidence]
    non_evidence_types = [e.type for e in sig.edges.values() if not e.evidence]
    conditional = []
    if evidence_types:
        conditional.append({
            "if": {"properties": {"type": {"enum": evidence_types}}, "required": ["type"]},
            "then": {"allOf": base_rules},
        })
    if non_evidence_types:
        conditional.append({
            "if": {"properties": {"type": {"enum": non_evidence_types}}, "required": ["type"]},
            "then": {
                "required": ["skeleton_kind", "similarity"],
                "not": {"anyOf": [{"required": [f]} for f in
                                  ("grade", "attestation", "confidence", "time", "claims", "weight")]},
            },
        })
    for esig in sig.edges.values():
        if esig.require_note_when_to:
            patterns = [sig.node_classes[c]["pattern"] for c in esig.require_note_when_to]
            conditional.append({
                "if": {
                    "properties": {"type": {"const": esig.type},
                                   "to": {"anyOf": [{"pattern": p} for p in patterns]}},
                    "required": ["type", "to"],
                },
                "then": {"required": ["note"],
                         "properties": {"note": {"type": "string", "minLength": 1}}},
            })
    edge_def["allOf"] = per_edge + conditional

    desc = data.get("description", "")
    note = "边 type 枚举与 if/then 条件约束由 spec/framework/edge-signatures.yaml 生成（tools/graphlint generate），勿手改。"
    if note not in desc:
        data["description"] = (desc + " " + note).strip()
    return data


def render_schema_text(sig: Signatures) -> str:
    return json.dumps(build_schema(sig), ensure_ascii=False, indent=2) + "\n"


def render_doc_text(sig: Signatures) -> str:
    text = DOC_PATH.read_text(encoding="utf-8")
    renders = {
        "edge-table": render_edge_table(sig),
        "edge-constraints": render_constraints(sig),
        "invariants": render_invariants(sig),
    }
    found: set[str] = set()

    def repl(match: re.Match[str]) -> str:
        name = match.group("name")
        if name not in renders:
            return match.group(0)
        found.add(name)
        return f"{match.group(1)}\n{renders[name]}\n{match.group(4)}"

    new_text = BLOCK_RE.sub(repl, text)
    missing = set(renders) - found
    if missing:
        raise SystemExit(f"object-model.md 缺少 GENERATED 标记：{', '.join(sorted(missing))}")
    return new_text


def generate(check: bool = False) -> int:
    sig = load()
    schema_text = render_schema_text(sig)
    doc_text = render_doc_text(sig)

    current_schema = GRAPH_SCHEMA_PATH.read_text(encoding="utf-8")
    current_doc = DOC_PATH.read_text(encoding="utf-8")
    drift = []
    if current_schema != schema_text:
        drift.append(str(GRAPH_SCHEMA_PATH))
    if current_doc != doc_text:
        drift.append(str(DOC_PATH))

    if check:
        if drift:
            print("生成物与 edge-signatures.yaml 不一致：")
            for path in drift:
                print(f"  - {path}")
            print("运行 py -3 -m graphlint generate 重新生成。")
            return 1
        print("生成物与 edge-signatures.yaml 一致。")
        return 0

    if current_schema != schema_text:
        GRAPH_SCHEMA_PATH.write_text(schema_text, encoding="utf-8")
        print(f"已更新 {GRAPH_SCHEMA_PATH.relative_to(REPO_ROOT)}")
    if current_doc != doc_text:
        DOC_PATH.write_text(doc_text, encoding="utf-8")
        print(f"已更新 {DOC_PATH.relative_to(REPO_ROOT)}")
    if not drift:
        print("无需更新：生成物已与 edge-signatures.yaml 一致。")
    return 0
